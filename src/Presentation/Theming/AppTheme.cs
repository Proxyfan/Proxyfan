namespace Proxyfan.Presentation.Theming;

/// <summary>
///     The user-visible theme variants offered by Proxyfan.
/// </summary>
public enum AppTheme
{
    /// <summary>
    ///     Follow the operating system theme; switches automatically when the OS theme changes.
    /// </summary>
    System,

    /// <summary>
    ///     Light theme with bright background and dark text.
    /// </summary>
    Light,

    /// <summary>
    ///     Dark theme with dark background and light text.
    /// </summary>
    Dark,
}
